/** Relative luminance (sRGB) to pick a readable glyph colour. */
export function luminance(color: string): number {
  const n = parseInt(color.slice(1), 16);
  const chan = (v: number) => {
    const c = v / 255;
    return c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4;
  };
  return 0.2126 * chan((n >> 16) & 255) + 0.7152 * chan((n >> 8) & 255) + 0.0722 * chan(n & 255);
}

export function contrastRatio(a: string, b: string): number {
  const [l1, l2] = [luminance(a), luminance(b)].sort((x, y) => y - x);
  return (l1 + 0.05) / (l2 + 0.05);
}

/** Issues a designer would flag: low contrast, text too long for an icon. */
export function checkIcon(spec: IconSpec): string[] {
  const notes: string[] = [];
  const bg = spec.plate.kind === "none" ? spec.background.from : spec.plate.color;
  if (contrastRatio(spec.glyphColor, bg) < 3) notes.push("El símbolo apenas contrasta con el fondo; cuesta leerlo en el móvil.");
  if (spec.glyph.kind === "letter" && spec.glyph.text.length > 2) notes.push("Tres letras se leen mal a 60 px; usa una o dos.");
  if (spec.glyphScale > 0.8) notes.push("El símbolo casi toca el borde; Google Play recorta el icono en círculo.");
  return notes;
}
