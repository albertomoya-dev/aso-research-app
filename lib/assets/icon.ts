export type SymbolName = keyof typeof SYMBOLS;
export const SYMBOL_NAMES = Object.keys(SYMBOLS) as SymbolName[];

const hex = z.string().regex(/^#[0-9a-fA-F]{6}$/);

export const iconSpecSchema = z.object({
  version: z.literal(1),
  background: z.object({
    kind: z.enum(["solid", "linear", "radial"]),
    from: hex,
    to: hex,
    /** Degrees, 0 = top to bottom, 90 = left to right. */
    angle: z.number().min(0).max(360),
  }),
  glyph: z.discriminatedUnion("kind", [
    z.object({ kind: z.literal("letter"), text: z.string().min(1).max(3), weight: z.union([z.literal(600), z.literal(700), z.literal(800)]) }),
    z.object({ kind: z.literal("symbol"), name: z.enum(SYMBOL_NAMES as [SymbolName, ...SymbolName[]]) }),
  ]),
  glyphColor: hex,
  /** Glyph size as a fraction of the icon side. */
  glyphScale: z.number().min(0.3).max(0.9),
  plate: z.object({ kind: z.enum(["none", "circle", "rounded"]), color: hex, scale: z.number().min(0.4).max(0.95) }),
  /** A soft highlight at the top, like classic iOS icons. */
  gloss: z.boolean(),
  /** Drop shadow under the glyph. */
  shadow: z.boolean(),
});
export type IconSpec = z.infer<typeof iconSpecSchema>;

/** Initials of the app name, without articles. */
export function initials(title: string): string {
  const clean = title.split(/[:\-–—|(]/)[0].trim();
  const parts = clean.split(/\s+/).filter((p) => p && !/^(the|el|la|los|las|de|del|un|una|app|a|an)$/i.test(p));
  const first = parts[0] ?? clean;
  return (first[0] ?? "A").toUpperCase();
}

export function defaultIconSpec(title: string): IconSpec {
  return {
    version: 1,
    background: { kind: "linear", from: "#5e6ad2", to: "#3b44a8", angle: 35 },
    glyph: { kind: "letter", text: initials(title), weight: 800 },
    glyphColor: "#ffffff",
    glyphScale: 0.58,
    plate: { kind: "none", color: "#ffffff", scale: 0.7 },
    gloss: true,
    shadow: true,
  };
}

